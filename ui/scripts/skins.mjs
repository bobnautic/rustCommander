#!/usr/bin/env node
// Maintenance for the built-in skins in src/skins/:
//
//   node scripts/skins.mjs check     validate every skin, print warnings and a contrast report
//   node scripts/skins.mjs format    sort the tokens of every skin like the token list
//   node scripts/skins.mjs schema    regenerate src/skins/skin.schema.json from the token list
//   node scripts/skins.mjs docs      regenerate docs/src/reference/skin-tokens.md from the token list
//   node scripts/skins.mjs check path/to/my-skin.json …    check other skin files
//
// Loads the TypeScript sources through Vite, like tests/unit.mjs.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const skinsDir = join(root, 'src', 'skins');
const [cmd = 'check', ...files] = process.argv.slice(2);

const vite = await createServer({ root, logLevel: 'error', server: { middlewareMode: true, hmr: false }, appType: 'custom', optimizeDeps: { noDiscovery: true } });
const { TOKENS, GROUPS } = await vite.ssrLoadModule('/src/lib/skins/tokens.ts');
const engine = await vite.ssrLoadModule('/src/lib/skins/engine.ts');

const builtinFiles = () =>
  readdirSync(skinsDir)
    .filter((f) => f.endsWith('.json') && f !== 'skin.schema.json')
    .map((f) => join(skinsDir, f));
const read = (f) => JSON.parse(readFileSync(f, 'utf8'));

let failed = 0;

if (cmd === 'format') {
  for (const f of builtinFiles()) {
    const skin = read(f);
    for (const v of ['light', 'dark']) {
      if (!skin[v]) continue;
      const sorted = {};
      for (const t of TOKENS) if (t.name in skin[v]) sorted[t.name] = skin[v][t.name];
      for (const k of Object.keys(skin[v])) if (!(k in sorted)) sorted[k] = skin[v][k];
      skin[v] = sorted;
    }
    writeFileSync(f, JSON.stringify(skin, null, 2) + '\n');
    console.log(`formatted ${basename(f)}`);
  }
} else if (cmd === 'schema') {
  const tokenProps = (kindFilter) => {
    const props = {};
    for (const t of TOKENS) {
      props[t.name] = {
        description: `${t.doc} (group: ${t.group})`,
        ...(t.kind === 'color' ? { $ref: '#/$defs/color' } : { $ref: '#/$defs/shadow' }),
      };
    }
    return props;
  };
  const schema = {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: 'https://raw.githubusercontent.com/bobnautic/rustcommander/main/ui/src/skins/skin.schema.json',
    title: 'Rust Commander skin',
    description: 'A skin for Rust Commander. See docs/src/guide/creating-skins.md. This file is generated by `node scripts/skins.mjs schema`.',
    type: 'object',
    required: ['id', 'name'],
    additionalProperties: false,
    properties: {
      $schema: { type: 'string' },
      id: { type: 'string', pattern: engine.ID_RE.source, description: 'Unique id: a-z, 0-9, - and _ (also the file name).' },
      name: { type: 'string', minLength: 1, maxLength: 80, description: 'Name shown in the skin gallery.' },
      description: { type: 'string', maxLength: 500 },
      author: { type: 'string', maxLength: 500 },
      version: { type: 'string', maxLength: 500 },
      license: { type: 'string', maxLength: 500 },
      extends: { type: 'string', pattern: engine.ID_RE.source, description: 'Id of the skin this one builds on (default: "default").' },
      style: {
        type: 'object',
        additionalProperties: false,
        properties: {
          fontUi: { type: 'string', description: 'CSS font-family of the user interface.' },
          fontMono: { type: 'string', description: 'CSS font-family of monospaced text.' },
          radius: { type: 'integer', minimum: engine.STYLE_LIMITS.radius[0], maximum: engine.STYLE_LIMITS.radius[1], description: 'Corner radius of buttons and inputs (px).' },
          panelRadius: { type: 'integer', minimum: engine.STYLE_LIMITS.panelRadius[0], maximum: engine.STYLE_LIMITS.panelRadius[1], description: 'Corner radius of panels, menus and dialogs (px).' },
          density: { enum: engine.DENSITIES, description: 'Row height of the file lists.' },
          listFontSize: { type: 'integer', minimum: engine.STYLE_LIMITS.listFontSize[0], maximum: engine.STYLE_LIMITS.listFontSize[1], description: 'Font size of the file lists (px).' },
          stripes: { type: 'boolean', description: 'Alternating row backgrounds in the file lists.' },
        },
      },
      light: { $ref: '#/$defs/variant', description: 'Token values of the light variant.' },
      dark: { $ref: '#/$defs/variant', description: 'Token values of the dark variant.' },
    },
    $defs: {
      color: {
        type: 'string',
        description: 'A CSS color: #rgb, #rrggbb, #rrggbbaa, rgb(), rgba(), hsl(), hsla(), black, white or transparent.',
        pattern: '^\\s*(#[0-9a-fA-F]{3,8}|(rgb|rgba|hsl|hsla)\\([^()]*\\)|black|white|transparent)\\s*$',
      },
      shadow: { type: 'string', description: 'A CSS box-shadow (lengths and colors) or "none".' },
      variant: { type: 'object', additionalProperties: false, properties: tokenProps() },
    },
  };
  writeFileSync(join(skinsDir, 'skin.schema.json'), JSON.stringify(schema, null, 2) + '\n');
  console.log(`wrote skin.schema.json (${TOKENS.length} tokens in ${GROUPS.length} groups)`);
} else if (cmd === 'docs') {
  const titles = { base: 'Surfaces', text: 'Text', accent: 'Accent', selection: 'Selection and cursor', status: 'Status', palette: 'Palette', files: 'File icons', chrome: 'Menu bar and function key bar', terminal: 'Terminal', syntax: 'Syntax highlighting', editor: 'Editor' };
  const def = read(join(skinsDir, 'default.json'));
  const lines = [
    '# Skin tokens',
    '',
    '<!-- Generated by `node ui/scripts/skins.mjs docs` from ui/src/lib/skins/tokens.ts. Do not edit by hand. -->',
    '',
    'Every color a skin can set. Each token is a CSS custom property (`--name`) and goes into the',
    '`light` and/or `dark` object of a skin file — see [Creating skins](../guide/creating-skins.md).',
    '',
    'A token a skin leaves out comes from its base skin. When the skin sets a token that another one',
    'is **derived from**, the derived token is computed from the new value instead (unless the skin sets',
    'it too). *Optional* tokens have no value until a skin sets one.',
    '',
  ];
  for (const g of GROUPS) {
    lines.push(`## ${titles[g]}`, '');
    if (g === 'palette') lines.push('Nine hues that file icons, status colors, the terminal and the syntax highlighting are derived from. Setting just the palette gives a skin consistent colors everywhere.', '');
    if (g === 'chrome') lines.push('All optional: they let a skin color the menu bar and the function keys differently from the rest of the chrome (the classic cyan bars of *Retro Blue*).', '');
    lines.push('| Token | Used for | Derived from | Default light | Default dark |', '|---|---|---|---|---|');
    for (const t of TOKENS.filter((x) => x.group === g)) {
      const from = t.optional ? '*optional*' : (t.from ?? []).map((f) => `\`${f}\``).join(', ') || '—';
      const val = (v) => (v === undefined ? '—' : `\`${v}\``);
      lines.push(`| \`${t.name}\` | ${t.doc.replace(/\|/g, '\\|')} | ${from} | ${val(def.light[t.name])} | ${val(def.dark[t.name])} |`);
    }
    lines.push('');
  }
  lines.push(
    '## Style',
    '',
    'Not colors: the `style` object of a skin applies to both variants.',
    '',
    '| Key | Values | Default |',
    '|---|---|---|',
    `| \`fontUi\` | CSS font-family list of the user interface | the system font |`,
    `| \`fontMono\` | CSS font-family list for paths, permissions, code | the system monospace font |`,
    `| \`radius\` | corner radius of buttons and inputs, ${engine.STYLE_LIMITS.radius.join('–')} px | \`6\` |`,
    `| \`panelRadius\` | corner radius of panels, menus and dialogs, ${engine.STYLE_LIMITS.panelRadius.join('–')} px | \`9\` |`,
    `| \`density\` | row height of the file lists: ${engine.DENSITIES.map((d) => `\`"${d}"\``).join(', ')} | \`"normal"\` |`,
    `| \`listFontSize\` | font size of the file lists, ${engine.STYLE_LIMITS.listFontSize.join('–')} px | \`13\` |`,
    '| `stripes` | `true` for alternating row backgrounds (`row-alt`) | `false` |',
    '',
  );
  const target = join(root, '..', 'docs', 'src', 'reference', 'skin-tokens.md');
  writeFileSync(target, lines.join('\n'));
  console.log(`wrote ${target}`);
} else if (cmd === 'check') {
  const paths = files.length ? files.map((f) => resolve(f)) : builtinFiles();
  const byId = new Map();
  for (const f of builtinFiles()) {
    const v = engine.validateSkin(read(f));
    if (v.skin) byId.set(v.skin.id, v.skin);
  }
  const lookup = (id) => byId.get(id);
  for (const f of paths) {
    const v = engine.validateSkin(read(f));
    if (!v.skin) {
      failed++;
      console.log(`✘ ${basename(f)}: ${v.errors.join('; ')}`);
      continue;
    }
    if (v.skin.id !== basename(f, '.json') && !files.length) console.log(`  ! ${basename(f)}: file name should be ${v.skin.id}.json`);
    byId.set(v.skin.id, v.skin);
    const variants = engine.variantsOf(v.skin, lookup);
    console.log(`${v.warnings.length ? '!' : '✔'} ${v.skin.name} (${v.skin.id}) – ${variants.join(' + ')}`);
    for (const w of v.warnings) console.log(`    warning: ${w}`);
    for (const scheme of variants) {
      const r = engine.resolveSkin(v.skin, lookup, scheme);
      const low = engine
        .contrastReport(r)
        .filter((c) => !c.ok)
        .map((c) => `${c.what} ${c.ratio.toFixed(2)} < ${c.min}`);
      console.log(`    ${scheme}: ${low.length ? 'low contrast: ' + low.join(', ') : 'contrast ok'}`);
      if (low.length && !files.length) failed++;
    }
  }
} else {
  console.log(`unknown command ${cmd}`);
  failed++;
}

await vite.close();
process.exit(failed ? 1 : 0);
